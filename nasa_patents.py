# 1. Prepare Text Features (Title)
vectorizer = TfidfVectorizer(stop_words='english')
X_title = vectorizer.fit_transform(df['Title'])

# 2. Prepare Categorical Features (Center)
# One-hot encode the 'Center' column
X_center = pd.get_dummies(df['Center'])

# 3. Combine Features
# We use hstack because X_title is a sparse matrix
X_combined = scipy.sparse.hstack([X_title, X_center.values])
y = df['Status']

# 4. Split the data
X_train, X_test, y_train, y_test = train_test_split(X_combined, y, test_size=0.2, random_state=42)

# 5. Train the model
model = RandomForestClassifier(random_state=42)
model.fit(X_train, y_train)

