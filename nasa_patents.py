from xgboost import XGBClassifier
from sklearn.preprocessing import LabelEncoder
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score
import scipy.sparse

# 1. Filter data to only 'Application' and 'Issued' to avoid label gaps
mask = df['Status'].isin(['Application', 'Issued'])
df_filtered = df[mask].copy()

# 2. Re-prepare features for filtered data
vectorizer = TfidfVectorizer(stop_words='english')
X_title_f = vectorizer.fit_transform(df_filtered['Title'])
X_center_f = pd.get_dummies(df_filtered['Center'])
X_combined_f = scipy.sparse.hstack([X_title_f, X_center_f.values])

# 3. Encode labels (will now be 0 and 1)
le = LabelEncoder()
y_encoded_f = le.fit_transform(df_filtered['Status'])

# 4. Split and Train
X_train, X_test, y_train, y_test = train_test_split(
    X_combined_f, y_encoded_f, test_size=0.2, random_state=42)

xgb = XGBClassifier(eval_metric='logloss')
xgb.fit(X_train, y_train)

y_pred_xgb = xgb.predict(X_test)
print("XGBoost Accuracy (Binary):", accuracy_score(y_test, y_pred_xgb))
